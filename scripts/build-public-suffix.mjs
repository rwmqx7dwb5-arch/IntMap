#!/usr/bin/env node
/* Builds js/public-suffix-data.js from the Public Suffix List (https://publicsuffix.org/list/, MPL-2.0).
 *   node scripts/build-public-suffix.mjs [path-to-public_suffix_list.dat]   (no argument: download the list)
 * WHY IT EXISTS: js/atlas-mcp-oauth.js must decide whether an OAuth endpoint is on the issuer's own registrable domain.
 * «Last two labels» says a.co.jp and b.co.jp are one site; only the PSL knows co.jp is a suffix.
 * Only rules that a «last label» default cannot express are kept (two or more labels, wildcards, exceptions), in ASCII
 * (punycode) form because that is what URL().hostname returns. The output is deterministic for a given list. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'js', 'public-suffix-data.js');
const SRC = 'https://publicsuffix.org/list/public_suffix_list.dat';

export function compactRules(text) {
  const rules = new Set();
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim().split(/\s/)[0];
    if (!line || line.startsWith('//')) continue;
    const neg = line[0] === '!', body = neg ? line.slice(1) : line;
    const wild = body.startsWith('*.');
    let host; try { host = new URL('https://' + (wild ? body.slice(2) : body)).hostname; } catch (_) { continue; }
    const rule = (neg ? '!' : '') + (wild ? '*.' : '') + host;
    if (neg || wild || host.includes('.')) rules.add(rule);
  }
  return [...rules].sort();
}

const arg = process.argv[2];
const text = arg ? fs.readFileSync(arg, 'utf8') : await (await fetch(SRC)).text();
const version = (/^\/\/ VERSION: (.+)$/m.exec(text) || [])[1] || 'unknown';
const commit = (/^\/\/ COMMIT: (.+)$/m.exec(text) || [])[1] || 'unknown';
const rules = compactRules(text);
fs.writeFileSync(OUT, `/* GENERATED by scripts/build-public-suffix.mjs — do not edit.
 * Public Suffix List, ${rules.length} rules of two or more labels / wildcards / exceptions (ASCII form).
 * Source: ${SRC}   VERSION ${version}   COMMIT ${commit}
 * Licence: MPL-2.0 (https://mozilla.org/MPL/2.0/). Refresh: node scripts/build-public-suffix.mjs */
export const PSL_VERSION = ${JSON.stringify(version)};
export const PSL_RULES = ${JSON.stringify(rules.join(' '))};
`);
console.log('wrote', OUT, rules.length, 'rules, list version', version);
