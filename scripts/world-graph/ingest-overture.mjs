#!/usr/bin/env node
/* ============================================================================
 *  scripts/world-graph/ingest-overture.mjs — a window of an Overture release → SQL for the persistent world graph
 * ----------------------------------------------------------------------------
 *  node scripts/world-graph/ingest-overture.mjs --theme places --type place --bbox 129.8,32.3,131.1,34.0 \
 *       --where '[{"field":"names.primary","op":"contains","value":"セミコン"}]' --out ingest.sql
 *
 *  The rows of ONE window (js/gis-overture.js query()) become, as idempotent SQL:
 *    world_graph_nodes       one per feature, `ids.gers` = Overture's identifier, the position Overture states
 *    world_graph_id_history  (ref, 'gers', id, release) with the source records Overture stated for the row
 *  and every statement first asks world_graph_adopt_id() which object the id belongs to — so an id Overture
 *  re-issued (its own figure: ~6.5 % a month) lands on the node that already holds the same source record, instead
 *  of making a second node. Nothing is matched by name or position.
 *
 *  Run the output as service_role (the tables are written by nobody else):  supabase db query -f ingest.sql
 *  Running it twice is one row each. ⚠ A node's `ids` is MERGED (the new gers replaces the old; every old id stays
 *  in the history), its facts are merged, its position and name are the latest release's.
 * ==========================================================================*/
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const q = (v) => (v == null ? 'null' : "'" + String(v).replace(/\u0000/g, '').replace(/'/g, "''") + "'");
const j = (v) => q(JSON.stringify(v == null ? null : v)) + '::jsonb';
const num = (v) => (typeof v === 'number' && isFinite(v) ? String(v) : 'null');

/* worldNodes() result → one transaction of statements */
export function toSql(nodesResult, meta) {
  const m = meta || {};
  const out = ['-- IntMap world graph · Overture ' + (m.release || '') + ' · ' + (m.theme || '') + '/' + (m.type || '') + ' · ' + nodesResult.nodes.length + ' objects',
    '-- generated by scripts/world-graph/ingest-overture.mjs — idempotent; run as service_role', 'begin;'];
  const hist = new Map(nodesResult.history.map((h) => [h.ref + '\u0000' + h.id, h]));
  for (const n of nodesResult.nodes) {
    const h = hist.get(n.ref + '\u0000' + n.ids.gers);
    const id = n.ids.gers, rel = h ? h.release : (m.release || ''), recs = h ? h.source_records : [];
    const adopt = 'public.world_graph_adopt_id(' + [q(n.ref), q('gers'), q(id), q(rel), j(recs)].join(', ') + ')';
    out.push(
      'insert into public.world_graph_nodes (ref, type, kind, name, country, lng, lat, provenance, ids, facts, sources) values (' +
      [adopt, q(n.type), q(n.kind), q(n.name), q(n.country), num(n.lng), num(n.lat), q(n.provenance), j(n.ids), j(n.facts), j(n.sources)].join(', ') + ')\n' +
      '  on conflict (ref) do update set kind = excluded.kind, name = excluded.name, country = coalesce(excluded.country, public.world_graph_nodes.country),\n' +
      '    lng = excluded.lng, lat = excluded.lat, provenance = excluded.provenance, ids = public.world_graph_nodes.ids || excluded.ids,\n' +
      '    facts = public.world_graph_nodes.facts || excluded.facts, sources = excluded.sources, updated_at = now();');
    if (h) {
      out.push('insert into public.world_graph_id_history (ref, scheme, ext_id, release, status, source_records, observed) values (' +
        [adopt, q('gers'), q(id), q(rel), q(h.status), j(recs), q(h.observed)].join(', ') + ')\n' +
        '  on conflict (ref, scheme, ext_id, release) do update set status = excluded.status, source_records = excluded.source_records, observed = excluded.observed;');
    }
  }
  out.push('commit;');
  return out.join('\n') + '\n';
}

async function main() {
  const a = process.argv.slice(2), get = (k) => { const i = a.indexOf('--' + k); return i >= 0 ? a[i + 1] : null; };
  const theme = get('theme'), type = get('type'), bbox = (get('bbox') || '').split(',').map(Number), out = get('out');
  if (!theme || !type || bbox.length !== 4 || !out) { console.error('usage: --theme <t> --type <t> --bbox w,s,e,n [--where <json>] --out <file.sql>'); process.exit(2); }
  const { makeGisOverture } = await import('../../js/gis-overture.js');
  const O = makeGisOverture({});
  const r = await O.query({ theme, type, bbox, where: get('where') ? JSON.parse(get('where')) : null });
  if (!r.ok) { console.error('query refused:', JSON.stringify(r)); process.exit(1); }
  const w = O.worldNodes(r);
  if (!w.ok) { console.error('worldNodes refused:', JSON.stringify(w)); process.exit(1); }
  fs.writeFileSync(out, toSql(w, { release: r.release.version, theme, type }));
  console.log(r.count + ' objects → ' + out + ' (release ' + r.release.version + ', ' + r.read.bytes + ' bytes read in ' + r.read.ms + ' ms)');
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
