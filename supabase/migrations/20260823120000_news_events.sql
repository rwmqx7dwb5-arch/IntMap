--  10. ROW LEVEL SECURITY
-- ----------------------------------------------------------------------------
--  読める: 公開の地図に出るものは全部（未ログインでも地図が出せなければならない）。
--  書ける: service_role だけ。例外は saved_news_events で、そこは本人だけ。
--  ⚠ news_cluster_decisions は admin だけ。モデルの生の応答と費用が入る。
-- ─────────────────────────────────────────────────────────────────────────────
alter table public.news_sources           enable row level security;
alter table public.news_source_feeds      enable row level security;
alter table public.news_articles          enable row level security;
alter table public.news_events            enable row level security;
alter table public.news_event_articles    enable row level security;
alter table public.news_cluster_decisions enable row level security;
alter table public.news_event_i18n        enable row level security;
alter table public.saved_news_events      enable row level security;

drop policy if exists news_sources_select_all on public.news_sources;
create policy news_sources_select_all on public.news_sources
  for select to anon, authenticated using (true);

drop policy if exists news_source_feeds_select_all on public.news_source_feeds;
create policy news_source_feeds_select_all on public.news_source_feeds
  for select to anon, authenticated using (true);

drop policy if exists news_articles_select_active on public.news_articles;
create policy news_articles_select_active on public.news_articles
  for select to anon, authenticated using (status = 'active');

drop policy if exists news_events_select_all on public.news_events;
create policy news_events_select_all on public.news_events
  for select to anon, authenticated using (true);

drop policy if exists news_event_articles_select_all on public.news_event_articles;
create policy news_event_articles_select_all on public.news_event_articles
  for select to anon, authenticated using (true);

drop policy if exists news_event_i18n_select_all on public.news_event_i18n;
create policy news_event_i18n_select_all on public.news_event_i18n
  for select to anon, authenticated using (true);

-- 判定の監査は admin だけ。profiles.is_admin を見るのは既存の表と同じ形。
drop policy if exists news_cluster_decisions_admin on public.news_cluster_decisions;
create policy news_cluster_decisions_admin on public.news_cluster_decisions
  for select to authenticated
  using (exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.is_admin));

-- ⚠ 運用者の Merge / Split / Reassign（`admin.html` の News Events タブ・docs/NEWS-EVENTS.md §11）は
--   まだ存在しない。**その UI と同じ変更で** `geo_pins` と同じ形の
--   `for all to authenticated using (public.is_admin())` を足すこと——
--   使う相手が無いうちに書き込み privilege を配ると、**誰も試していない権限**が本番に居座る。
--   今この表を書くのは service_role（ingest）だけである。
drop policy if exists saved_news_events_rw_own on public.saved_news_events;
create policy saved_news_events_rw_own on public.saved_news_events
  for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

-- ─────────────────────────────────────────────────────────────────────────────
--  11. GRANTS
-- ----------------------------------------------------------------------------
--  ⚠ ポリシーだけでは読めない。grant が要る（#R155 が同じ穴を塞いでいる）。
--  ⚠ 書き込みの grant は anon / authenticated に一切与えない。service_role は RLS を迂回する。
-- ─────────────────────────────────────────────────────────────────────────────
revoke all on public.news_sources,           public.news_source_feeds,
              public.news_articles,          public.news_events,
              public.news_event_articles,    public.news_cluster_decisions,
              public.news_event_i18n,        public.saved_news_events
  from anon, authenticated;

grant select on public.news_sources, public.news_source_feeds, public.news_articles,
                public.news_events,  public.news_event_articles, public.news_event_i18n
  to anon, authenticated;

grant select on public.news_cluster_decisions to authenticated;

grant select, insert, update, delete on public.saved_news_events to authenticated;

-- ⚠⚠ service_role への表の grant を**明示する**。
--   baseline の `grant all on all tables in schema public to service_role` は
--   **その時点のスナップショット**であって、あとから作られた表には届かない。
--   ここを既定の privilege 頼みにすると、ingest が本番でだけ書けない——
--   しかも RLS を迂回する role なので、失敗の理由が「権限」だと分かりにくい。
grant select, insert, update, delete on
  public.news_sources,           public.news_source_feeds,
  public.news_articles,          public.news_events,
  public.news_event_articles,    public.news_cluster_decisions,
  public.news_event_i18n,        public.saved_news_events
  to service_role;

grant usage, select on sequence public.news_articles_id_seq,
                                public.news_events_id_seq,
                                public.news_source_feeds_id_seq,
                                public.news_cluster_decisions_id_seq,
                                public.saved_news_events_id_seq
  to service_role;
