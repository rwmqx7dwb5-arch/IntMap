/* ============================================================================
 *  IntMap · js/readiness-check.js — WILL INTMAP WORK ON THIS DEVICE, ON THIS NETWORK?   (wave4-sales)
 * ----------------------------------------------------------------------------
 *  MEASURED 2026-10-13, BEFORE THIS FILE. An organisation deciding whether to adopt IntMap (a school, a
 *  newsroom, a company, a town hall) had to ask its IT staff one question nobody could answer from
 *  IntMap's pages: «will it work behind OUR filter, on OUR devices?». The school pages said «allow the
 *  site and the map, data and font services it loads — the privacy policy lists them» and «WebGL», and
 *  stopped there. The list was prose; nothing ran on the device in question. The nightly check
 *  (scripts/upstream-liveness.mjs) asks the 113 requested hosts from a GitHub runner, which says
 *  whether a SUPPLIER is up — never whether a school's network lets a classroom reach it.
 *
 *  THIS FILE IS THE CHECK, RUN WHERE IT MATTERS: in the browser that will open the map.
 *    · the device — the drawing context the map engine requires (MAP_CONTEXT), whether it is hardware
 *      accelerated, background workers, an offline copy, storage;
 *    · the network — ONE representative request to every host the browser code requests (the same
 *      `probe` the nightly check uses, scripts/outbound-hosts.json, shipped in data/connection-ledger.json),
 *      sorted into what the FIRST VIEW needs (index.html's own preconnect declaration), IntMap's own
 *      backend (Atlas, sign-in, the enquiry form), and the data layers;
 *    · last night's answer for each host it could not reach (data/service-status.json, read by
 *      js/service-status.js) — «unreachable here, answering last night» is the network's doing and is
 *      something IT can allow; «unreachable here and silent last night too» is the supplier's.
 *  Read by js/readiness-page.js (readiness.html, generated by scripts/org-pages.mjs) and by Atlas
 *  (`system.readiness`, js/atlas-cap-system.js). scripts/org-pages.mjs uses probeRows() (which sorts by tierOf()) to write
 *  the page's allowlist, so the page and Atlas sort a host into the same tier by the same rule.
 *
 *  ⚠ WHAT ONE REQUEST CAN AND CANNOT SAY. Each probe is a `no-cors` GET: the browser reports whether an
 *  answer came back, never what it said. So:
 *    · «reached» means the network carried a request to that host and something answered. A filter that
 *      answers IN THE SITE'S PLACE (a block page served through an inspecting proxy) cannot be told apart
 *      from the site here — the page says so in words, it is not hidden;
 *    · «not reached» is an observed failure (the browser refused to hand back any answer: DNS, a reset,
 *      a refused TLS handshake) and «no answer in time» is a clock that ran out. They are reported apart
 *      (.agents/rules/one-pass-or-a-reason.md §5 — 「確認できなかった」 is not 「失敗した」), and neither
 *      is retried: the report is a photograph of this device at this minute, not a judgement of a host.
 *  Nothing is sent to IntMap by the check. The report leaves the device only if the reader copies it or
 *  attaches it to an enquiry themselves.
 *  No words here: the page's words are in the page (en + jp, scripts/org-pages-text.mjs), Atlas's in its entry.
 * ==========================================================================*/
import { hostMatches } from './host-match.js';

/* The drawing context the map engine asks for. CANON: maplibre-gl's own declaration — `export type ContextType =
   'webgl2'` in node_modules/maplibre-gl/src/ui/map.ts (6.13.0: «contextType is restricted to 'webgl2'»).
   tests/wave4-sales-checks.test.mjs holds this equal to it, so the day the engine asks for another context
   (its comment names WebGPU) the check is red instead of testing the wrong thing. */
export const MAP_CONTEXT = 'webgl2';

/* How long one probe may take before it is reported as «no answer in time». CANON: scripts/upstream-liveness.mjs
   TIMEOUT_MS (the nightly check's own clock) — held equal by the test, so «no answer in time» means the same on the
   runner and on the reader's device. EXPIRES with that constant. */
export const PROBE_TIMEOUT_MS = 20000;

/* How many probes run at once. CANON: scripts/upstream-liveness.mjs CONCURRENCY (held equal by the test). Each
   probe asks a DIFFERENT host, so a browser's per-host limit (six connections) never binds; 16 keeps the whole check
   to a few seconds on a working network and to (hosts / 16) x PROBE_TIMEOUT_MS on one that drops every packet. */
export const PROBE_CONCURRENCY = 16;

/* the order a reader reads the tiers in: what the map needs to open, what Atlas and sign-in need, then each layer */
export const TIERS = Object.freeze(['first', 'backend', 'layer']);

/** The host names a list of preconnect addresses names (index.html's `<link rel="preconnect">` — «the hosts every
    cold start needs before it can draw anything», #R192). Anything that is not an absolute http(s) URL is skipped. */
export function firstViewHosts(hrefs) {
  const out = [];
  for (const h of hrefs || []) {
    let u; try { u = new URL(String(h)); } catch (_) { continue; }
    if (!/^https?:$/.test(u.protocol)) continue;
    const name = u.hostname.toLowerCase();
    if (!out.includes(name)) out.push(name);
  }
  return out;
}

/** Which tier a ledger host belongs to: IntMap's own backend, a host the first view preconnects to, or a data layer's. */
function tierOf(host, ctx) {
  const c = ctx || {};
  if (c.backend && hostMatches(host, c.backend)) return 'backend';
  if ((c.firstView || []).some((h) => hostMatches(host, h))) return 'first';
  return 'layer';
}

/** The probes the check runs: every row of the derived connection ledger (data/connection-ledger.json) the browser
    REQUESTS and that declares a probe address, with its tier — sorted by tier, then host, so two readers list them
    in the same order. Rows that are links or behind a switch that is off carry no probe and are not asked. */
export function probeRows(rows, ctx) {
  const out = [];
  for (const r of rows || []) {
    if (!r || r.form !== 'disclosure' || typeof r.probe !== 'string') continue;
    let u; try { u = new URL(r.probe); } catch (_) { continue; }
    if (u.protocol !== 'https:') continue;
    out.push({ host: r.host, url: r.probe, what: r.what || '', whatJp: r.whatJp || r.what || '', tier: tierOf(r.host, ctx) });
  }
  return out.sort((a, b) => TIERS.indexOf(a.tier) - TIERS.indexOf(b.tier) || (a.host < b.host ? -1 : a.host > b.host ? 1 : 0));
}

/** One probe: `reached` (an answer came back — any answer), `blocked` (the browser refused to return one) or
    `timeout` (no answer within the clock). `ms` is the time to the answer, only when there was one. */
async function probeOne(p, opt) {
  const o = opt || {};
  const fetchImpl = o.fetchImpl || globalThis.fetch;
  const now = o.now || (() => (globalThis.performance && performance.now ? performance.now() : Date.now()));
  const timeoutMs = o.timeoutMs || PROBE_TIMEOUT_MS;
  const ctl = typeof AbortController === 'function' ? new AbortController() : null;
  const t0 = now();
  let timer = null;
  const clock = new Promise((res) => { timer = setTimeout(() => { res('timeout'); if (ctl) ctl.abort(); }, timeoutMs); });
  let verdict;
  try {
    verdict = await Promise.race([
      Promise.resolve().then(() => fetchImpl(p.url, { mode: 'no-cors', cache: 'no-store', credentials: 'omit', redirect: 'follow', referrerPolicy: 'no-referrer', signal: ctl ? ctl.signal : undefined }))
        .then(() => 'reached', () => 'blocked'),
      clock,
    ]);
  } finally { clearTimeout(timer); }
  return { host: p.host, url: p.url, tier: p.tier, what: p.what, whatJp: p.whatJp, verdict, ms: verdict === 'reached' ? Math.round(now() - t0) : null };
}

/** Every probe, PROBE_CONCURRENCY at a time; `onResult(result, index, done)` is told as each one finishes. */
export async function probeAll(probes, opt) {
  const o = opt || {};
  const list = probes || [];
  const out = new Array(list.length);
  let next = 0, done = 0;
  const lanes = Math.max(1, Math.min(o.concurrency || PROBE_CONCURRENCY, list.length));
  await Promise.all(Array.from({ length: list.length ? lanes : 0 }, async () => {
    while (next < list.length) {
      const k = next++;
      out[k] = await probeOne(list[k], o);
      done++;
      if (o.onResult) { try { o.onResult(out[k], k, done); } catch (_) { /* a listener's error is its own */ } }
    }
  }));
  return out;
}

/** What this browser offers the map. `null` for a reading that could not be made (never reported as «no»). */
export function deviceReport(doc, win) {
  const w = win || {};
  const make = () => { try { return doc.createElement('canvas'); } catch (_) { return null; } };
  const drop = (gl) => { try { const x = gl && gl.getExtension('WEBGL_lose_context'); if (x) x.loseContext(); } catch (_) { /* nothing to free */ } };
  let gl = null, accelerated = null, maxTexture = null;
  try { const c = make(); gl = c ? c.getContext(MAP_CONTEXT) : null; } catch (_) { gl = null; }
  if (gl) {
    try { maxTexture = gl.getParameter(gl.MAX_TEXTURE_SIZE) || null; } catch (_) { maxTexture = null; }
    /* a context refused ONLY when a major performance caveat applies is a software renderer (SwiftShader, a virtual
       desktop without a GPU): the map draws, slowly. A second canvas, because a canvas hands back the same context
       whatever attributes the second call asks for. */
    try { const c2 = make(); const fast = c2 ? c2.getContext(MAP_CONTEXT, { failIfMajorPerformanceCaveat: true }) : null; accelerated = !!fast; drop(fast); } catch (_) { accelerated = null; }
    drop(gl);
  }
  let storage = null;
  try { const k = 'intmap_readiness_probe'; w.localStorage.setItem(k, '1'); w.localStorage.removeItem(k); storage = true; } catch (_) { storage = false; }
  const nav = w.navigator || {};
  return {
    map: !!gl,
    context: MAP_CONTEXT,
    accelerated,
    maxTexture,
    workers: typeof w.Worker === 'function',
    offline: !!(w.isSecureContext && nav && 'serviceWorker' in nav),
    storage,
    online: typeof nav.onLine === 'boolean' ? nav.onLine : null,
  };
}

/** The verdict. `lastNight(host)` is last night's row for a host (js/service-status.js upstreamFor) or null when it
    could not be read — then a host this device could not reach is «unknown», never «the supplier's fault».
      ready      the map can draw and every host was reached
      partial    the map can draw, but Atlas/sign-in or some layers' hosts were not reached
      not-ready  the device cannot draw the map, or a host the first view needs was not reached from here */
export function assess(device, results, lastNight) {
  const rows = (results || []).map((r) => {
    if (r.verdict === 'reached') return { ...r, supplier: null };
    let n = null; try { n = lastNight ? lastNight(r.host) : null; } catch (_) { n = null; }
    const supplier = !n ? 'unknown' : (n.verdict === 'dead' || n.verdict === 'refused') ? 'down' : n.verdict === 'alive' ? 'up' : 'unknown';
    return { ...r, supplier, lastNight: n ? { verdict: n.verdict, why: n.why || null, lastAlive: n.lastAlive || null } : null };
  });
  const tiers = {};
  for (const t of TIERS) {
    const mine = rows.filter((r) => r.tier === t);
    tiers[t] = { total: mine.length, reached: mine.filter((r) => r.verdict === 'reached').length, missing: mine.filter((r) => r.verdict !== 'reached') };
  }
  const missing = rows.filter((r) => r.verdict !== 'reached');
  /* the hosts IT can act on: not reached here, and not known to be down at the supplier */
  const allow = missing.filter((r) => r.supplier !== 'down');
  const supplierDown = missing.filter((r) => r.supplier === 'down');
  const canDraw = !!(device && device.map && device.workers);
  const firstBlocked = tiers.first.missing.filter((r) => r.supplier !== 'down');
  const overall = !canDraw || firstBlocked.length ? 'not-ready' : missing.length ? 'partial' : 'ready';
  return { overall, canDraw, tiers, missing, allow, supplierDown, checked: rows.length, reached: rows.length - missing.length };
}
