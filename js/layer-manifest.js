export function catalog() {
  return LAYERS.map((l) => ({ id: l.id, key: l.key || null, shelf: l.shelf, label: l.label || null,
    rest: !!l.rest, on: !!l.on, share: !!l.share, lazy: l.lazy ? l.lazy.slice() : [] }));
}
