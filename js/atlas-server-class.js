/* ============================================================================
 *  IntMap · where a capability can run when no page is open   (js/atlas-server-class.js)
 * ----------------------------------------------------------------------------
 *  A durable job (supabase/functions/atlas-jobs) runs after the tab is gone. A capability named in it falls into one of
 *  three classes, and the class is DERIVED from the capability's own registry record — never listed by hand:
 *
 *    'read'      reads and changes nothing, asks nobody, starts no model work. It may have a SERVER TWIN
 *                (supabase/functions/_shared/atlas-server-caps.js) that does the same read with no page; with one it runs on
 *                the server, without one it is refused by name.
 *    'parkable'  changes the map or the session (a layer, the camera, a panel, the clock …), is reversible, needs no
 *                confirmation, asks nobody and saves no file. It cannot run on a server — there is no map there — so the job
 *                SAVES the operation and the page applies it, through the same executor a turn uses, the next time the
 *                reader returns. The task ends `done` with `result.parked`; it is not a smaller answer given as the whole.
 *    'page-only' everything else — a write the reader must confirm, a file, a question to the reader, another model's work.
 *                Refused at planning, by name.
 *
 *  The effect class is js/cap-bridge.js `effectClass` — the same one that decides what a program may call — so a job, a
 *  program and a turn agree on what a capability does. NO IMPORTS BUT THAT ONE; the mirror for the Edge Function is
 *  generated by scripts/sync-atlas-cap-classes.mjs (check: tests/exec-platform-checks.test.mjs).
 * ==========================================================================*/
import { effectClass } from './cap-bridge.js';

export const SERVER_CLASSES = Object.freeze(['read', 'parkable', 'page-only']);

export function serverClass(cap) {
  if (!cap || cap.withdrawn) return 'page-only';
  const f = cap.facets || {};
  /* the controls of the job system are the job's own: a job that stops, changes or starts jobs is not something to save for later */
  if (/^jobs[.]/.test(String(cap.id))) return 'page-only';
  if (f.asksUser || f.delegates || f.savesFile) return 'page-only';
  const cls = effectClass(cap);
  if (cls === 'read') return 'read';
  if (cls === 'state' && cap.confirmation === 'none') return 'parkable';
  return 'page-only';
}
