test('③ og-image.jpg is a real JPEG, light enough to unfurl, and the head states its real size', () => {
  const info = brand.jpegInfo(brand.SOCIAL_IMAGE);
  assert.ok(info.jpeg, 'og-image.jpg must be a JPEG (it was a 1 MB PNG under a .jpg name)');
  /* ⚠ (no-ad-hoc-hardcoding §4) observation: WhatsApp is reported (not documented by Meta) to drop the preview
     picture above ~300 kB; the other card readers allow megabytes, so this is the tightest. Lapses: if that
     reader's limit moves. Canonical: here. */
  assert.ok(info.bytes <= 300 * 1024, 'og-image.jpg is ' + info.bytes + ' bytes — over the ~300 kB a WhatsApp preview is reported to take');
  const html = read('index.html');
  assert.ok(html.includes('property="og:image:width" content="' + info.width + '"') && html.includes('property="og:image:height" content="' + info.height + '"'),
    'index.html states a size that is not the file\'s');
  assert.ok(info.width >= 1200, 'the large card wants at least 1200 px across');
});

test('④ no number is typed into the brand\'s or the posts\' words', () => {
  /* the tokens that contain a digit and are NOT a fact IntMap could drift from — each says why */
  const ALLOWED = [
    [/CShapes 2\.0/g, 'the dataset\'s own name (Schvitz et al. 2022 publish it as «CShapes 2.0»)'],
    [/\?embed=1/g, 'the embed address grammar itself (js/embed-mode.js), not a quantity'],
    [/3-D/g, 'a word'],
  ];
  const strings = [];
  const walk = (v, where) => { if (typeof v === 'string') strings.push([where, v]); else if (v && typeof v === 'object') for (const [k, x] of Object.entries(v)) walk(x, where + '.' + k); };
  walk(BRAND, 'BRAND');
  walk(POSTS, 'POSTS');
  for (const [where, s] of strings) {
    let t = s.replace(/\{[^{}]*\}/g, '');
    for (const [re] of ALLOWED) t = t.replace(re, '');
    assert.ok(!/\d/.test(t), where + ' types a number: «' + s.slice(0, 120) + '» — use a placeholder filled from the file that owns it');
  }
});

