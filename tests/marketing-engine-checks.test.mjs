/* ============================================================================
 *  marketing-engine — the brand's one source, the social picture, and the historical-map entry pages
 * ----------------------------------------------------------------------------
 *  ① every file scripts/brand.mjs writes says what it would write (index.html head, docTitle/docDesc,
 *    manifest, README tagline, press kit, launch drafts) — and the manifest's own derivation agrees
 *  ② the landing page's headline IS the brand's tagline (two generators, one promise)
 *  ③ og-image.jpg is a real JPEG, light enough to unfurl, and the head states its real size
 *  ④ no number is typed into the brand's or the posts' words — they come from the files that own them
 *  ⑤ a post's link carries utm tags only where IntMap counts them, and those survive the counter's rule
 *  ⑥ the entry pages, generated by running the map's own border code, NAME A YEAR AND A PLACE and say
 *    what history says there (.agents/rules/historical-verification.md §2-1/§2-2)
 *  ⑦ the pages are coherent: runs partition the years, neighbours differ, links resolve, the map link
 *    opens the page's own region and date, hreflang is reciprocal, nothing executes, the sitemap is exact
 *  ⑧ the build writes them (vite.config.js), and the country-table fields the generator reads are the
 *    ones js/countries-ui.js reads
 * ========================================================================== */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { join, dirname, posix } from 'node:path';
import { fileURLToPath } from 'node:url';
const { COUNTRY_HUB } = await import('../scripts/country-pages.mjs');   /* (country-pages) the history hub links it */

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(ROOT, p), 'utf8');
const norm = (s) => s.replace(/\r\n/g, '\n');

const brand = await import('../scripts/brand.mjs');
const { BRAND } = await import('../scripts/brand-text.mjs');
const { POSTS } = await import('../scripts/launch-text.mjs');

test('① every file the brand writes says what scripts/brand.mjs would write', async () => {
  const F = brand.brandFacts();
  const out = await brand.outputs(F);
  for (const [rel, body] of Object.entries(out)) {
    assert.ok(existsSync(join(ROOT, rel)), rel + ' is missing — run node scripts/brand.mjs --write');
    assert.equal(norm(read(rel)), norm(body), rel + ' differs from what scripts/brand.mjs writes — run node scripts/brand.mjs --write');
  }
  const M = await import('../scripts/build-app-manifest.mjs');
  assert.deepEqual(M.check(), [], 'manifest.webmanifest and its sources disagree');
  const doc = M.readDocument();
  const en = brand.words('en', F);
  assert.equal(doc.description, en.description, 'the manifest reads a description that is not the brand\'s');
  /* the app writes these over the head at run time: they must be the head's words, not a third answer */
  for (const [file, lang] of [['js/locales/ui.en.js', 'en'], ['js/locales/ui.jp.js', 'jp']]) {
    const W = brand.words(lang, F);
    const t = read(file);
    assert.equal(/docTitle:"([^"]*)"/.exec(t)[1], W.title, file + ' docTitle');
    assert.equal(/docDesc:"([^"]*)"/.exec(t)[1], W.description, file + ' docDesc');
  }
  /* the head is the one block, and the old promise is gone from it */
  const html = read('index.html');
  assert.equal(html.split(brand.HEAD_BEGIN).length, 2, 'one generated head block');
  assert.equal((html.match(/<title>[^<]*<\/title>/g) || []).length, 1, 'index.html has exactly one title element');
  for (const tag of ['og:title', 'og:description', 'og:image', 'og:url', 'og:image:width', 'og:image:height']) {
    assert.equal((html.match(new RegExp('property="' + tag + '"', 'g')) || []).length, 1, 'index.html states ' + tag + ' once');
  }
  for (const tag of ['twitter:card', 'twitter:title', 'twitter:description', 'twitter:image']) assert.ok(html.includes('name="' + tag + '"'), 'index.html has ' + tag);
  assert.ok(html.includes('<link rel="canonical" href="__INTMAP_SITE_URL__">'), 'index.html has a canonical that the build fills');
  const ld = JSON.parse(/<script type="application\/ld\+json">([^<]*)<\/script>/.exec(html)[1]);
  assert.equal(ld['@type'], 'WebApplication');
  assert.equal(ld.description, en.description);
  assert.deepEqual(ld.inLanguage, F.langTags, 'the app\'s languages, from the language registry');
});

